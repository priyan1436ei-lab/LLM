/**
 * Seed data — foods (FITTRACK AI, Indian-first reference database).
 *
 * Every nutrient column below is per 100 g of the EDIBLE PORTION, AS EATEN. Cooked dishes
 * therefore carry their cooked weight basis: cooked rice is ~130 kcal/100 g, not the
 * ~350 kcal/100 g of raw grain. Water gained during cooking, and the gravy or tempering
 * medium, are already reflected in the numbers — do not "correct" them back to raw.
 *
 * Provenance tiers used in `sourceName` / `sourceUrl`:
 *  1. Published table row — the food (or a close equivalent) appears in the Indian Food
 *     Composition Tables 2017 (IFCT, NIN Hyderabad) or USDA FoodData Central.
 *  2. Recipe composite — no published row exists for the dish as eaten, so the values are
 *     computed from the ingredient rows of IFCT 2017 / USDA FDC for one stated,
 *     representative home-style preparation. `preparationNote` says what was assumed.
 *
 * Values are rounded to the precision the reference supports. Nothing here is a
 * measurement of a specific brand or kitchen; where a dish varies a lot by recipe, a
 * defensible representative preparation was chosen and is described in the note.
 */

export interface SeedServing {
  /** Human label shown in the UI, e.g. '1 katori', '1 idli', '1 cup'. */
  label: string;
  /** CANONICAL unit code accepted by the conversion engine (see src/lib/units.ts). */
  unit: string;
  /** Quantity of `unit` this serving describes. Always > 0. */
  amount: number;
  /** Grams of edible portion for `amount` of `unit`. Always > 0. */
  grams: number;
  /** True for household measures whose weight varies (katori, cup, piece, handful...). */
  isApproximate: boolean;
  /** At most ONE serving per food may set this — the portion used when none is given. */
  isDefault?: boolean;
}

export interface SeedFood {
  canonicalName: string;
  /** 'south_indian' | 'north_indian' | 'indian_general' | 'global' */
  region: string;
  /** Must resolve to a slug exported in `foodCategories` below. */
  categorySlug: string;
  aliases: { alias: string; language?: string; region?: string }[];
  /** Nutrients per 100 g of the edible portion, as eaten. */
  per100g: {
    caloriesKcal: number;
    proteinG: number;
    carbsG: number;
    fatG: number;
    fiberG: number;
    sugarG: number;
    sodiumMg: number;
  };
  /** REQUIRED: which reference the numbers came from. */
  sourceName: string;
  sourceUrl?: string;
  /** 1-2 sentences on how the dish is prepared and what the numbers assume. */
  preparationNote: string;
  servings: SeedServing[];
}

